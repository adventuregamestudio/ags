#define TOOL_NAME_DEF "crmbuild v0.1.0"

const char *BIN_STRING = TOOL_NAME_DEF " - AGS room builder\n"
                                       "Copyright (c) 2026 AGS Team and contributors";

const char *HELP_STRING =
    //------------------------------------------------------------------------------|
    "Usage:\n"
    "  crmbuild <GAME.AGF> <ROOM-NUMBER> -o <OUT.CRM> [--script <ROOM.O>]\n"
    "      builds the room file from the room sources in Rooms/<ROOM-NUMBER>/\n"
    "      next to GAME.AGF (data.xml, background and mask images), as the editor\n"
    "      does; a compiled room script, if given, is put into the room file.\n"
    "  crmbuild <GAME.AGF> <ROOM-NUMBER> --header <OUT.ASH> [--prepend <FILE>]\n"
    "      writes the declarations of the room's named objects, hotspots and\n"
    "      areas, after the text of FILE: the editor appends them to the game's\n"
    "      _AutoGenerated.ash when it compiles a room script.\n"
    "\n"
    "Options:\n"
    "  -v, --verbose          print operation details";

static HError LoadTextFile(const String &filename, String &text)
{
    auto in = File::OpenFileRead(filename);
    if (!in)
        return new Error(String::FromFormat("Failed to open %s", filename.GetCStr()));
    text = String::FromStream(in.get(), SIZE_MAX);
    return HError::None();
}

static HError WriteHeader(const RoomXml &room, const String &prepend_file, const String &out_file)
{
    String text;
    if (!prepend_file.IsEmpty())
    {
        HError err = LoadTextFile(prepend_file, text);
        if (!err)
            return err;
    }
    text.Append(MakeRoomScriptHeader(GetRoomScriptNames(room)));

    auto out = File::CreateFile(out_file);
    if (!out)
        return new Error(String::FromFormat("Failed to open %s for writing", out_file.GetCStr()));
    out->Write(text.GetCStr(), text.GetLength());
    return HError::None();
}

static HError BuildRoom(const String &agf_file, const String &room_dir, const RoomXml &room, const String &script_file,
                        const String &out_file)
{
    AGS::AGF::AGFReader reader;
    HError err = reader.Open(agf_file.GetCStr());
    if (!err)
        return err;
    RoomBuildGame game;
    err = ReadRoomBuildGame(reader, game);
    if (!err)
        return err;

    RoomData data;
    err = ConvertRoomXml(room, game, data);
    if (!err)
        return err;
    std::vector<String> warnings;
    err = LoadRoomImages(room_dir, room, game, data, warnings);
    for (const auto &w : warnings)
        printf("Warning: %s\n", w.GetCStr());
    if (!err)
        return err;

    if (!script_file.IsEmpty())
    {
        auto in = File::OpenFileRead(script_file);
        if (!in)
            return new Error(String::FromFormat("Failed to open %s", script_file.GetCStr()));
        data.CompiledScript.reset(ccScript::CreateFromStream(in.get()));
        if (!data.CompiledScript)
            return new Error(String::FromFormat("Failed to read compiled script %s", script_file.GetCStr()));
    }
    FinishRoomData(data);

    auto out = File::CreateFile(out_file);
    if (!out)
        return new Error(String::FromFormat("Failed to open %s for writing", out_file.GetCStr()));
    // NOTE: "compiled with" must match the version written into the main game data, as the editor does
    HRoomFileError room_err = WriteRoomData(&data, nullptr, out.get(), kRoomVersion_Current, ACI_VERSION_STR);
    if (!room_err)
        return new Error(
            String::FromFormat("Failed to write %s: %s", out_file.GetCStr(), room_err->FullMessage().GetCStr()));
    return HError::None();
}

int main(int argc, char *argv[])
{
    printf("%s\n", BIN_STRING);

    CmdLineOpts::ParseResult cmdargs = CmdLineOpts::Parse(argc, argv, {"-o", "--script", "--header", "--prepend"});
    if (cmdargs.HelpRequested)
    {
        printf("%s\n", HELP_STRING);
        return 0;
    }
    if (cmdargs.PosArgs.size() < 2)
    {
        printf("Error: not enough arguments\n%s\n", HELP_STRING);
        return -1;
    }

    const String agf_file = cmdargs.PosArgs[0];
    const int room_number = StrUtil::StringToInt(cmdargs.PosArgs[1], -1);
    if (room_number < 0)
    {
        printf("Error: invalid room number: %s\n", cmdargs.PosArgs[1].GetCStr());
        return -1;
    }
    String out_crm, script_file, out_header, prepend_file;
    for (const auto &opt : cmdargs.OptWithValue)
    {
        if (opt.first == "-o")
            out_crm = opt.second;
        else if (opt.first == "--script")
            script_file = opt.second;
        else if (opt.first == "--header")
            out_header = opt.second;
        else if (opt.first == "--prepend")
            prepend_file = opt.second;
    }
    if (out_crm.IsEmpty() == out_header.IsEmpty())
    {
        printf("Error: give either -o or --header\n%s\n", HELP_STRING);
        return -1;
    }
    const bool verbose = cmdargs.Opt.count("-v") || cmdargs.Opt.count("--verbose");

    // Allegro RGB shifts, which image loading and color conversion use
    set_rgb_shifts(10, 5, 0, 11, 5, 0, 16, 8, 0, 16, 8, 0, 24);

    const String room_dir = Path::ConcatPaths(Path::GetParent(Path::MakeAbsolutePath(agf_file)),
                                              String::FromFormat("Rooms/%d", room_number));
    const String data_file = Path::ConcatPaths(room_dir, "data.xml");
    if (verbose)
        printf("Room sources: %s\n", room_dir.GetCStr());

    RoomXml room;
    HError err = ReadRoomXmlFile(data_file, room);
    if (err)
    {
        if (!out_header.IsEmpty())
            err = WriteHeader(room, prepend_file, out_header);
        else
            err = BuildRoom(agf_file, room_dir, room, script_file, out_crm);
    }
    if (!err)
    {
        printf("Error: %s\n", err->FullMessage().GetCStr());
        return -1;
    }
    printf("Done: %s\n", (out_header.IsEmpty() ? out_crm : out_header).GetCStr());
    return 0;
}
