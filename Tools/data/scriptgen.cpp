// Generates a game object declaration in the form of a *macro*.
// check_prefix is an optional prefix that has to be present in an original
// name; if it's set then names without such prefix will be skipped.
// The macro name will be <script_name>, where "script_name" is read from the
// object data, have check_prefix stripped and converted to uppercase.
// The macro value is made equal to object's ID (numeric index).
static String DeclareEntityAsMacro(const EntityRef &ent, const char *check_prefix = nullptr)
{
    String name = ent.ScriptName;
    // if check_prefix is defined, skip those which do not have it;
    // if it has one, remove the prefix and proceed
    if (check_prefix)
    {
        if (!name.StartsWith(check_prefix))
            return "";
        name.ClipLeft(strlen(check_prefix));
    }
    // skip if the name is empty or begins with a digit (eg. c500 would cause error),
    // as Editor's Tasks.AppendCharactersToHeader does
    if (name.IsEmpty() || std::isdigit(static_cast<unsigned char>(name[0])))
        return "";

    name.MakeUpper();
    return String::FromFormat("#define %s %d\n", name.GetCStr(), ent.ID);
}

// Generates game object declarations of the given type, in the form
// "import <type_name> *<name>;" as Editor's Tasks.Append*ToHeader do.
// type_name defines the script name of the type, with its qualifiers (e.g. "readonly Character").
// If array_name is provided then also declares array of objects of that type;
// without objects, the array is a dummy array of 1 null pointer, which prevents
// "undefined symbol" errors (Editor's Tasks.AppendCharactersToHeader and others).
// If array_base is > 0, it will be added to the array size in declaration.
// If macro_prefix is provided then each object also gets a macro, declared before it
// (see DeclareEntityAsMacro), as in Editor's Tasks.AppendCharactersToHeader.
static String DeclareEntities(const std::vector<EntityRef> &ents,
    const char *type_name, const char *array_name = nullptr, const int array_base = 0,
    const char *macro_prefix = nullptr)
{
    if (ents.size() == 0)
    {
        if (array_name)
            return String::FromFormat("import %s *%s[1];\n", type_name, array_name);
        return "";
    }

    String header;
    if (array_name)
        header.AppendFmt("import %s *%s[%zu];\n",
            type_name, array_name, ents.size() + array_base);

    for (const auto &ent : ents)
    {
        if (macro_prefix)
            header.Append(DeclareEntityAsMacro(ent, macro_prefix));
        String name = ent.ScriptName;
        if (name.IsEmpty())
            continue;
        header.AppendFmt("import %s *%s;\n", type_name, name.GetCStr());
    }
    return header;
}

// Generates game object declarations in the form of *macros*,
// see DeclareEntityAsMacro.
static String DeclareEntitiesAsMacros(const std::vector<EntityRef> &ents,
    const char *check_prefix = nullptr)
{
    if (ents.size() == 0)
        return "";

    String header;
    for (const auto &ent : ents)
    {
        header.Append(DeclareEntityAsMacro(ent, check_prefix));
    }
    return header;
}

// Generates game object declarations in the form of *enum*.
// enum_name defines the name of the enumeration.
// dummy_name is the member declared when there are no others, as the enum must
// have something in it (Editor's Tasks.AppendCursorsToHeader).
// first_members is optional text with constant members that go first, before
// the objects (Editor's Tasks.AppendFontsToHeader).
// The actual constant name will be <script_name>, where "script_name" is read
// from the object data. The constant values are made equal to object's ID
// (numeric index).
static String DeclareEntitiesAsEnum(const std::vector<EntityRef> &ents,
    const char *enum_name, const char *dummy_name, const char *first_members = nullptr)
{
    String header;
    header.AppendFmt("enum %s {\n", enum_name);
    bool first = true;
    if (first_members)
    {
        header.Append(first_members);
        first = false;
    }
    for (const auto &ent : ents)
    {
        String name = ent.ScriptName;
        if (name.IsEmpty())
            continue;

        header.AppendFmt("%s  %s = %d", first ? "" : ",\n", name.GetCStr(), ent.ID);
        first = false;
    }
    if (first)
    {
        // no elements, make sure the enum has something in it
        header.AppendFmt("%s = 99  // $AUTOCOMPLETEIGNORE$ ", dummy_name);
    }
    header.Append("\n};\n");
    return header;
}

// Generates GUI and GUI Control declarations.
// For backward compatibility also declares uppercase macros which translate
// into the call to FindGUIID function, used to lookup for GUI pointer using
// a "script name" string.
// The declarations are as in Editor's Tasks.AppendGUIsToHeader.
static String DeclareGUI(const std::vector<GUIRef> &guis)
{
    if (guis.size() == 0)
    {
        // Declare a dummy array of 1 null pointer, prevent "undefined symbol" errors
        return "import readonly GUI *gui[1];\n";
    }

    String header;
    header.AppendFmt("import readonly GUI *gui[%zu];\n", guis.size());

    String macro_name;
    for (const auto &gui : guis)
    {
        const String &gui_name = gui.ScriptName;
        if (gui_name.IsEmpty())
            continue;

        header.AppendFmt("import readonly GUI *%s;\n", gui_name.GetCStr());

        if (gui_name.GetAt(0) == 'g')
        {
            macro_name = gui_name.Mid(1);
            macro_name.MakeUpper();
            header.AppendFmt("#define %s FindGUIID(\"%s\")\n", macro_name.GetCStr(), macro_name.GetCStr());
        }

        for (const auto &ent : gui.Controls)
        {
            const String &obj_name = ent.ScriptName;
            if (obj_name.IsEmpty())
                continue;
            const String &class_name = ent.TypeName;
            header.AppendFmt("import readonly %s *%s;\n", class_name.GetCStr(), obj_name.GetCStr());
        }
    }
    return header;
}

// Generates whole game autoheader by merging various object and array declarations,
// in the order of Editor's Tasks.RegenerateScriptHeader: the order of declarations
// ends up in the compiled scripts' type info and table of contents.
// NOTE: the Editor lists characters, audio clips and views folder by folder,
// here they go in ID order; the two differ only for objects in subfolders.
String MakeGameAutoScriptHeader(const GameRef &game)
{
    String header;
    // Cursors (Tasks.AppendCursorsToHeader)
    header.Append(DeclareEntitiesAsEnum(game.Cursors, "CursorMode", "eDummyCursor__"));
    // Fonts (Tasks.AppendFontsToHeader)
    header.Append(DeclareEntitiesAsEnum(game.Fonts, "FontType", nullptr, "  eUndefinedFont = -2,  eNullFont = -1"));
    // Characters, each after its legacy macro, e.g. EGO for cEgo (Tasks.AppendCharactersToHeader)
    header.Append(DeclareEntities(game.Characters, "readonly Character", "character", 0, "c"));
    // Audio types (Tasks.AppendAudioClipTypesToHeader)
    header.Append(DeclareEntitiesAsEnum(game.AudioTypes, "AudioType", "eDummyAudioType__"));
    // Audio clips (Tasks.AppendAudioClipsToHeader)
    header.Append(DeclareEntities(game.AudioClips, "AudioClip"));
    // Inventory items, the array is 1-based (Tasks.AppendInventoryToHeader)
    header.Append(DeclareEntities(game.Inventory, "readonly InventoryItem", "inventory", 1));
    // Dialogs (Tasks.AppendDialogsToHeader)
    std::vector<EntityRef> dialogs; // TODO: look for better solution later
    std::copy(game.Dialogs.begin(), game.Dialogs.end(), std::back_inserter(dialogs));
    header.Append(DeclareEntities(dialogs, "readonly Dialog", "dialog"));
    // GUI (Tasks.AppendGUIsToHeader)
    header.Append(DeclareGUI(game.GUI));
    // Views (Tasks.AppendViewsToHeader)
    header.Append(DeclareEntitiesAsMacros(game.Views));
    return header;
}


