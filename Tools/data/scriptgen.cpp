//
// A port of the editor's Tasks.RegenerateScriptHeader, in the same order: the
// order of the declarations ends up in the compiled scripts' type info and
// table of contents.

// Declares an enum of the entities' script names; an enum must have a member
static void DeclareEnum(String &header, const std::vector<EntityRef> &ents, const char *enum_name,
                        const char *dummy_name)
{
    header.AppendFmt("enum %s {\n", enum_name);
    bool first = true;
    for (const auto &ent : ents)
    {
        if (ent.ScriptName.IsEmpty())
            continue;
        if (!first)
            header.Append(",\n");
        header.AppendFmt("  %s = %d", ent.ScriptName.GetCStr(), ent.ID);
        first = false;
    }
    if (first)
        header.AppendFmt("%s = 99  // $AUTOCOMPLETEIGNORE$ ", dummy_name);
    header.Append("\n};\n");
}

// Declares an array of pointers to the entities, then each named one; without
// entities, a dummy array of one null pointer prevents "undefined symbol" errors
template <typename TEntity>
static void DeclareObjects(String &header, const std::vector<TEntity> &ents, const char *type_name,
                           const char *array_name, size_t array_base = 0)
{
    if (ents.empty())
    {
        header.AppendFmt("import readonly %s *%s[1];\n", type_name, array_name);
        return;
    }
    header.AppendFmt("import readonly %s *%s[%zu];\n", type_name, array_name, ents.size() + array_base);
    for (const auto &ent : ents)
    {
        if (!ent.ScriptName.IsEmpty())
            header.AppendFmt("import readonly %s *%s;\n", type_name, ent.ScriptName.GetCStr());
    }
}

static void DeclareFonts(String &header, const std::vector<EntityRef> &fonts)
{
    header.Append("enum FontType {\n");
    header.Append("  eUndefinedFont = -2,");
    header.Append("  eNullFont = -1");
    for (const auto &font : fonts)
    {
        if (!font.ScriptName.IsEmpty())
            header.AppendFmt(",\n  %s = %d", font.ScriptName.GetCStr(), font.ID);
    }
    header.Append("\n};\n");
}

static void DeclareCharacters(String &header, const std::vector<CharacterRef> &chars)
{
    if (chars.empty())
    {
        header.Append("import readonly Character *character[1];\n");
        return;
    }
    header.AppendFmt("import readonly Character *character[%zu];\n", chars.size());
    for (const auto &ch : chars)
    {
        const String &name = ch.ScriptName;
        // the legacy macro, e.g. EGO for cEgo, unless it would start with a digit (c500)
        if (name.GetLength() > 1 && name[0] == 'c' && !std::isdigit(static_cast<unsigned char>(name[1])))
        {
            String macro = name.Mid(1);
            macro.MakeUpper();
            header.AppendFmt("#define %s %d\n", macro.GetCStr(), ch.ID);
        }
        if (!name.IsEmpty())
            header.AppendFmt("import readonly Character *%s;\n", name.GetCStr());
    }
}

static void DeclareGUIs(String &header, const std::vector<GUIRef> &guis)
{
    if (guis.empty())
    {
        header.Append("import readonly GUI *gui[1];\n");
        return;
    }
    header.AppendFmt("import readonly GUI *gui[%zu];\n", guis.size());
    for (const auto &gui : guis)
    {
        const String &name = gui.ScriptName;
        if (name.IsEmpty())
            continue;
        header.AppendFmt("import readonly GUI *%s;\n", name.GetCStr());
        // the legacy macro, which looks up the GUI by name
        if (name[0] == 'g')
        {
            String macro = name.Mid(1);
            macro.MakeUpper();
            header.AppendFmt("#define %s FindGUIID(\"%s\")\n", macro.GetCStr(), macro.GetCStr());
        }
        for (const auto &control : gui.Controls)
        {
            if (!control.ScriptName.IsEmpty())
                header.AppendFmt("import readonly %s *%s;\n", control.TypeName.GetCStr(), control.ScriptName.GetCStr());
        }
    }
}

String MakeGameAutoScriptHeader(const GameRef &game)
{
    String header;
    DeclareEnum(header, game.Cursors, "CursorMode", "eDummyCursor__");
    DeclareFonts(header, game.Fonts);
    DeclareCharacters(header, game.Characters);
    DeclareEnum(header, game.AudioTypes, "AudioType", "eDummyAudioType__");
    for (const auto &clip : game.AudioClips)
    {
        if (!clip.ScriptName.IsEmpty())
            header.AppendFmt("import AudioClip *%s;\n", clip.ScriptName.GetCStr());
    }
    // the inventory array has a dummy item at index 0
    DeclareObjects(header, game.Inventory, "InventoryItem", "inventory", 1);
    DeclareObjects(header, game.Dialogs, "Dialog", "dialog");
    DeclareGUIs(header, game.GUI);
    // NOTE: the editor lists a folder's views before its subfolders; the order of macros
    // doesn't matter to the compiled scripts
    for (const auto &view : game.Views)
    {
        if (view.ScriptName.IsEmpty())
            continue;
        String macro = view.ScriptName;
        macro.MakeUpper();
        header.AppendFmt("#define %s %d\n", macro.GetCStr(), view.ID);
    }
    return header;
}


