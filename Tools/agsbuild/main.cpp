struct BuildOptions
{
    static const uint32_t MinThreads = 1u;
    static const uint32_t MaxThreads = 32u;
    static const uint32_t DefThreads = 8u;

    // A directory where all the tool executables are located
    String SysDir;
    // A path to script API header
    String ApiAshPath;
    // Game project's source directory
    String SrcDir;
    // Game project's document file (Game.agf by default)
    String SrcAgf;
    // If agsbuild owns temporary output directory (must delete on cleanup)
    bool OwnTempDir = false;
    // Temporary directory for any intermediate output
    String TempDir;
    // Final output directory for deploying game build
    String OutDir;
    // Should we recreate spitefile by importing sprites from source image files,
    // even if one already exists.
    bool ReimportSprites = false;
    // Should we reimport all audio clips
    bool ReimportAudio = false;
    // Delete intermediate files on successful completion
    bool Cleanup = false;
    // Max threads used for running tasks (does not include main program thread)
    uint32_t TaskThreads = DefThreads;
    bool Verbose = false;
    // Build mode (overrides game project settings)
    bool BuildDebug = false;
    bool BuildRelease = false;
    // Treat what the tools cannot read from the project as errors
    bool Strict = false;
};

struct GameOptions
{
    String Name;
    String FileName;
    int UniqueID = 0;
    DataUtil::SpriteCompression SpriteCompression = DataUtil::SpriteCompression::kSprCompress_Deflate;
    bool SpriteOptimizeStorage = true;
};

struct ScriptCompilerOptions
{
    String GameCompilerVersion;
    String ApiVersion = "Highest";
    String CompatVersion = "Highest";
    bool EnforcePost262Scripting = true; // aka Object-oriented scripting
    bool EnforceNewStrings = true;
    bool EnforceNewAudio = true;
    bool OldDialogOptionsAPI = true;
    bool UnicodeMode = true; // game text in UTF-8
    bool DebugBuild = false;
};

const uint32_t BuildOptions::MinThreads;
const uint32_t BuildOptions::MaxThreads;
const uint32_t BuildOptions::DefThreads;

String MakeAGSCCFlags(const ScriptCompilerOptions &opts)
{
    return String::FromFormat("--override-version %s -A %s -C %s -fforceobjectbasedscript=%s -fforcenewstrings=%s -fforcenewaudio=%s -foldcustomdialogopt=%s %s %s",
        opts.GameCompilerVersion.GetCStr(),
        opts.ApiVersion.GetCStr(),
        opts.CompatVersion.GetCStr(),
        opts.EnforcePost262Scripting ? "1" : "0",
        opts.EnforceNewStrings ? "1" : "0",
        opts.EnforceNewAudio ? "1" : "0",
        opts.OldDialogOptionsAPI ? "1" : "0",
        opts.UnicodeMode ? "" : "--ascii",
        opts.DebugBuild ? "-g" : ""
        );
}

String MakeSpriteImportFlags(const GameOptions &opts)
{
    int sflags = 0;
    const char *compress;
    switch (opts.SpriteCompression)
    {
    case DataUtil::SpriteCompression::kSprCompress_None: compress = "none"; break;
    case DataUtil::SpriteCompression::kSprCompress_RLE: compress = "rle"; break;
    case DataUtil::SpriteCompression::kSprCompress_LZW: compress = "lzw"; break;
    case DataUtil::SpriteCompression::kSprCompress_Deflate:
    default:
        compress = "deflate"; break;
    }
    sflags |= 0x1 * opts.SpriteOptimizeStorage;
    return String::FromFormat("-z %s -s 0x%x", compress, sflags);
}

